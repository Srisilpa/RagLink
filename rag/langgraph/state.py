from typing import (
    TypedDict,
    List,
    Dict,
    Any,
)

from langchain_core.documents import (
    Document,
)


class GraphState(
    TypedDict,
    total=False,
):

    # ========================================================
    # ORIGINAL USER QUERY
    # ========================================================

    question: str


    # ========================================================
    # QUERY ROUTING TYPE
    #
    # rag
    # chat
    # time
    # date
    # calculator
    # web
    # ========================================================

    query_type: str



    # ========================================================
    # QUERY UNDERSTANDING
    # ========================================================

    rewritten_query: str


    expanded_queries: List[str]


    intent: str



    # ========================================================
    # ENTITY EXTRACTION
    # ========================================================

    entities: List[
        Dict[str, Any]
    ]



    # ========================================================
    # RETRIEVAL PLANNING
    # ========================================================

    retrieval_plan: Dict[
        str,
        Any,
    ]


    search_queries: List[str]


    document_types: List[str]


    retrieval_strategy: str



    # ========================================================
    # METADATA FILTERS
    # ========================================================

    metadata_filters: Dict[
        str,
        Any,
    ]



    # ========================================================
    # MULTI-QUERY / MULTI-INTENT
    # ========================================================

    sub_queries: List[
        Dict[str, Any]
    ]



    # ========================================================
    # RETRIEVAL OUTPUT
    # ========================================================

    retrieved_docs: List[
        Document
    ]



    retrieval_count: int



    # ========================================================
    # RERANKING OUTPUT
    # ========================================================

    reranked_docs: List[
        Document
    ]



    # ========================================================
    # CONTEXT COMPRESSION
    # ========================================================

    context: str


    context_count: int



    # ========================================================
    # EVIDENCE CHECK
    # ========================================================

    evidence_sufficient: bool



    # ========================================================
    # GENERATION OUTPUT
    # ========================================================

    answer: str



    # ========================================================
    # SOURCES
    # ========================================================

    sources: List[
        Dict[str, Any]
    ]



    # ========================================================
    # CACHE
    # ========================================================

    cache_hit: bool



    # ========================================================
    # PERFORMANCE
    # ========================================================

    latency: float



    # ========================================================
    # ERROR TRACKING
    # ========================================================

    error: str